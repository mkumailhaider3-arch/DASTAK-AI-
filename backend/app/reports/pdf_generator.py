import io
from datetime import datetime, timezone
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle


def generate_session_pdf(
    session: dict,
    documents: list[dict],
    readiness: dict,
    comparisons: list[dict],
    include_full_ocr: bool = False,
) -> bytes:
    """Generate a downloadable PDF analysis report using ReportLab."""
    buffer = io.BytesIO()
    doc = SimpleDocTemplate(buffer, pagesize=A4, title="DASTAK AI Analysis Report")
    styles = getSampleStyleSheet()
    story = []

    # Header
    story.append(Paragraph("DASTAK AI — Document Pre-Check Report", styles["Title"]))
    story.append(Paragraph("Smart Documents, Secure Future.", styles["Italic"]))
    story.append(Spacer(1, 8))

    # Prominent Disclaimer
    story.append(
        Paragraph(
            "<b>ACADEMIC PROTOTYPE DISCLAIMER:</b> This report is generated by an academic prototype only. "
            "It is NOT NADRA, is not connected to any government database, and does NOT verify identity "
            "or certify legal authenticity.",
            styles["Normal"],
        )
    )
    story.append(Spacer(1, 12))

    # Session Metadata
    now_str = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    story.append(Paragraph(f"<b>Application Type:</b> {session['application_type']}", styles["Normal"]))
    story.append(Paragraph(f"<b>Session ID:</b> {session['id']}", styles["Normal"]))
    story.append(Paragraph(f"<b>Generated At:</b> {now_str}", styles["Normal"]))
    story.append(Spacer(1, 12))

    # Readiness Score
    pct = readiness.get("percentage")
    score_text = (
        f"{pct:.1f}% ({readiness.get('total_score')} / {readiness.get('max_assessed_score')} assessed points)"
        if pct is not None
        else "Not assessed"
    )
    story.append(Paragraph(f"<b>{readiness.get('score_label', 'Prototype readiness score')}:</b> {score_text}", styles["Heading2"]))
    story.append(Paragraph(readiness.get("disclaimer", ""), styles["Normal"]))
    story.append(Spacer(1, 10))

    # Score Breakdown Table
    criteria_rows = [["Criterion", "Status", "Score"]]
    for c in readiness.get("criteria", []):
        score_col = f"{c['earned']} / {c['weight']}" if c["earned"] is not None else f"Not assessed ({c['weight']})"
        criteria_rows.append([c["name"], c["status"], score_col])
    t_crit = Table(criteria_rows, colWidths=[240, 100, 120])
    t_crit.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#123B5D")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
            ]
        )
    )
    story.append(t_crit)
    story.append(Spacer(1, 12))

    # Checklist
    story.append(Paragraph("Checklist Status", styles["Heading2"]))
    chk_rows = [["Category", "Status", "Matched Files"]]
    for item in readiness.get("checklist", []):
        chk_rows.append([item["label"], item["status"], ", ".join(item["matched_documents"]) or "—"])
    t_chk = Table(chk_rows, colWidths=[180, 90, 190])
    t_chk.setStyle(
        TableStyle(
            [
                ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#167D9A")),
                ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
                ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
                ("FONTSIZE", (0, 0), (-1, -1), 9),
            ]
        )
    )
    story.append(t_chk)
    story.append(Spacer(1, 12))

    # Files Analysed & Warnings
    story.append(Paragraph("Files Analysed & Quality Warnings", styles["Heading2"]))
    for d in documents:
        q = d.get("quality") or {}
        warnings = ", ".join(q.get("warnings", [])) if q.get("warnings") else "No heuristic warnings"
        story.append(
            Paragraph(
                f"• <b>{d['original_filename']}</b> ({d['selected_category']}): {warnings}",
                styles["Normal"],
            )
        )
    story.append(Spacer(1, 12))

    # Field Comparisons
    if comparisons:
        story.append(Paragraph("Cross-Document Field Comparisons", styles["Heading2"]))
        for comp in comparisons:
            story.append(
                Paragraph(
                    f"• <b>{comp['field_name']}</b>: {comp['status']} — {comp['explanation']}",
                    styles["Normal"],
                )
            )
        story.append(Spacer(1, 12))

    # Optional Full OCR Text (Off by default for privacy)
    if include_full_ocr:
        story.append(Paragraph("Full Extracted OCR Text (User Opt-In)", styles["Heading2"]))
        for d in documents:
            story.append(Paragraph(f"<b>{d['original_filename']}</b>", styles["Normal"]))
            ocr_safe = (d.get("ocr_text") or "No OCR text").replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            story.append(Paragraph(ocr_safe.replace("\n", "<br/>"), styles["Code"]))
            story.append(Spacer(1, 6))

    doc.build(story)
    return buffer.getvalue()
